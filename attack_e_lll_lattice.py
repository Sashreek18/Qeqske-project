# Pure-Python LLL implementation (Gram-Schmidt with rational arithmetic)
# ---------------------------------------------------------------------------
# We use Python's Fraction class for exact rational arithmetic so that
# LLL terminates correctly with no floating-point rounding errors.
# For n≤8 this is fast enough; at large n, one would use numpy or fpylll.

def _dot(u, v):
    """Exact integer / Fraction dot product."""
    return sum(ui * vi for ui, vi in zip(u, v))


def _gram_schmidt(B):
    """
    Gram–Schmidt orthogonalisation of rows of B.
    Returns (B_star, mu) where B_star[i] is the i-th GSO vector and
    mu[i][j] = <B[i], B_star[j]> / <B_star[j], B_star[j]>  for j < i.
    Uses Fraction for exactness.
    """
    n  = len(B)
    Bs = [None] * n   # Gram–Schmidt vectors (Fraction entries)
    mu = [[Fraction(0)] * n for _ in range(n)]

    for i in range(n):
        Bs[i] = [Fraction(x) for x in B[i]]
        for j in range(i):
            if Bs[j] is None:
                continue
            nrm_sq_j = _dot(Bs[j], Bs[j])
            if nrm_sq_j == 0:
                continue
            mu[i][j] = _dot([Fraction(x) for x in B[i]], Bs[j]) / nrm_sq_j
            Bs[i] = [Bs[i][k] - mu[i][j] * Bs[j][k] for k in range(len(B[0]))]

    return Bs, mu


def lll_reduce(B_input, delta=Fraction(3, 4)):
    """
    LLL basis reduction (Lenstra–Lenstra–Lovász, 1982).

    Input : B_input  — list of n integer row-vectors (the basis).
    Output: B        — LLL-reduced basis (same lattice, shorter rows).
    delta  : LLL delta parameter ∈ (1/4, 1).  Standard choice: 3/4.

    The first row of the returned basis is the shortest vector found by LLL;
    for well-conditioned instances (small noise, small n) it equals the
    unique shortest lattice vector.

    Uses exact rational arithmetic (Fraction) — correct for all inputs.
    """
    B = [list(row) for row in B_input]   # mutable copy of integer vectors
    n = len(B)

    k = 1
    while k < n:
        Bs, mu = _gram_schmidt(B)

        # Size reduction: round off large mu[k][j] coefficients
        for j in range(k - 1, -1, -1):
            c = int(mu[k][j] + Fraction(1, 2))   # round to nearest integer
            if c != 0:
                B[k] = [B[k][i] - c * B[j][i] for i in range(len(B[0]))]

        # Recompute GSO after size-reduction
        Bs, mu = _gram_schmidt(B)
        nrm_k   = _dot(Bs[k], Bs[k])
        nrm_km1 = _dot(Bs[k - 1], Bs[k - 1])

        # Lovász condition
        if nrm_k >= (delta - mu[k][k - 1] ** 2) * nrm_km1:
            k += 1
        else:
            # Swap rows k and k-1
            B[k], B[k - 1] = B[k - 1], B[k]
            k = max(k - 1, 1)

    return B


def vec_norm_sq(v):
    """Squared Euclidean norm (integer exact)."""
    return sum(x * x for x in v)


def vec_norm(v):
    return math.sqrt(vec_norm_sq(v))


# ---------------------------------------------------------------------------
# Build the q-ary primal lattice for the LWE instance t = A*s + e (column c)
# ---------------------------------------------------------------------------

def build_lwe_lattice(A, t_col, q, n):
    """
    Construct the 2n × 2n integer lattice basis for the primal attack on:
        A · s_col  +  e_col  ≡  t_col   (mod q)

    The embedding lattice is:

        B = [ q * I_n  |   0_n  ]   (rows 0 … n-1)
            [   A      |   I_n  ]   (rows n … 2n-1)

    A short vector in this lattice has the form (e_col, s_col) (after reduction
    mod q rows cancel).  Its length is ≈ sqrt(n) since |e_i|, |s_i| ≤ 1.

    We also augment with a "hint" row for t_col to allow the target subtraction:
        [t_col | -1_n ] added so that B · (s, 1) ≈ (-e, 0) is short.
    Here we use the simpler direct formulation instead.
    """
    dim = 2 * n
    B = [[0] * dim for _ in range(dim)]

    # Top-left block: q * I_n
    for i in range(n):
        B[i][i] = q

    # Bottom-left block: A  (using mod-q representatives centred around 0)
    for i in range(n):
        for j in range(n):
            # Centre A entries: use symmetric representatives in (-q/2, q/2]
            a = A[i][j] % q
            B[n + i][j] = a if a <= q // 2 else a - q

    # Bottom-right block: I_n
    for i in range(n):
        B[n + i][n + i] = 1

    return B


def extract_secret_from_lll(B_reduced, n, q, t_col, A, noise_bound=NOISE_BOUND):
    """
    After LLL reduction, the first few rows of B are shortest lattice vectors.
    A valid (e, s) pair has length ≤ sqrt(2n) * noise_bound  (since |e_i|,|s_i|≤1).

    We iterate rows of B_reduced in order of increasing norm, checking whether
    the right half [n:2n] of the row is a valid secret column (by verifying
    A*s - t_col has bounded residual).
    """
    # Sort rows by norm
    rows_by_norm = sorted(B_reduced, key=lambda r: vec_norm_sq(r))

    for row in rows_by_norm:
        # Try both the row and its negation (lattice is symmetric)
        for cand_vec in [row, [-x for x in row]]:
            s_cand = cand_vec[n:]   # right half = candidate secret column

            # Check all coefficients are small ({-1,0,1} or at most ±noise_bound)
            if any(abs(x) > noise_bound for x in s_cand):
                continue

            # Verify: A*s_cand ≈ t_col (mod q)
            resid = [(sum(A[i][j] * s_cand[j] for j in range(n)) - t_col[i]) % q
                     for i in range(n)]
            resid_sym = [min(r, q - r) for r in resid]
            if max(resid_sym) <= noise_bound:
                return s_cand   # found it

    return None   # LLL did not find a valid secret in this run


# ---------------------------------------------------------------------------
# Full secret recovery: run LLL per column of s
# ---------------------------------------------------------------------------

def recover_full_secret_lll(A, t, q, n, k, verbose=False):
    """
    For each column c of s, build the primal lattice, run LLL, extract s[:,c].
    Returns s_hat (n×k matrix) or None if any column fails.
    """
    s_hat = [[0] * k for _ in range(n)]

    for col in range(k):
        t_col = [t[i][col] for i in range(n)]

        if verbose:
            print(f"\n  [Column {col}] Building 2n×2n lattice (dim={2*n})...")

        B = build_lwe_lattice(A, t_col, q, n)

        if verbose:
            norms = [f"{vec_norm(r):.1f}" for r in B]
            print(f"           Basis row norms (pre-LLL): {norms}")

        t0 = time.perf_counter()
        B_red = lll_reduce(B)
        lll_time = (time.perf_counter() - t0) * 1000

        if verbose:
            norms_red = [f"{vec_norm(r):.1f}" for r in B_red]
            print(f"           Basis row norms (post-LLL): {norms_red}")
            print(f"           LLL time: {lll_time:.2f} ms")

        s_col = extract_secret_from_lll(B_red, n, q, t_col, A)

        if s_col is None:
            if verbose:
                print(f"           FAILED — LLL did not isolate s[:,{col}]")
            return None

        for row in range(n):
            s_hat[row][col] = s_col[row]

        if verbose:
            print(f"           Recovered s[:,{col}] = {s_col}")

    return s_hat


