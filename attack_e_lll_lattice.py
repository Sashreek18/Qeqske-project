    print(f"  Time per key — mean  : {statistics.mean(timings):.2f} ms")
    print(f"               — min   : {min(timings):.2f} ms")
    print(f"               — max   : {max(timings):.2f} ms")
    print(f"               — stdev : {statistics.stdev(timings):.2f} ms")
